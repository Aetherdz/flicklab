/**
 * Downloads the self-hosted font subsets used by the site.
 * Families: Saira Condensed (numerals), Inter Tight (EN UI/body),
 * IBM Plex Sans Arabic (AR UI/body).
 *
 * Only the latin and arabic subsets are kept, in woff2, latin-1 ranges dropped
 * where irrelevant. Output: public/fonts/*.woff2 + src/styles/fonts.css
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const UA =
  'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/131.0 Safari/537.36';
const API =
  'https://fonts.googleapis.com/css2?family=Saira+Condensed:wght@500;700&family=Inter+Tight:wght@400;500;600&family=IBM+Plex+Sans+Arabic:wght@400;500;600&display=swap';

const ROOT = join(import.meta.dirname, '..');
const OUT = join(ROOT, 'public', 'fonts');
const CSS_OUT = join(ROOT, 'src', 'styles', 'fonts.css');

/** Keep the arabic block and the basic-latin block; everything else is unused. */
const isArabic = (range) => range.includes('U+0600-06FF');
const isLatin = (range) => range.includes('U+0000-00FF');

const css = await (await fetch(API, { headers: { 'User-Agent': UA } })).text();
const blocks = css.split('@font-face').slice(1);

await mkdir(OUT, { recursive: true });

const faces = [];
for (const raw of blocks) {
  const family = /font-family:\s*'([^']+)'/.exec(raw)?.[1];
  const weight = /font-weight:\s*(\d+)/.exec(raw)?.[1];
  const url = /src:\s*url\((https:[^)]+)\)/.exec(raw)?.[1];
  const range = /unicode-range:\s*([^;]+);/.exec(raw)?.[1] ?? '';
  if (!family || !weight || !url) continue;
  const keep = isArabic(range) || isLatin(range);
  if (!keep) continue;

  const slug = `${family.toLowerCase().replace(/[^a-z0-9]+/g, '-')}-${weight}-${isArabic(range) ? 'ar' : 'lat'}`;
  const file = `${slug}.woff2`;
  const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
  await writeFile(join(OUT, file), buf);
  faces.push({ family, weight, file, range: range.trim() });
  console.log(`saved ${file} ${(buf.length / 1024).toFixed(1)} kB`);
}

const lines = [
  '/* Generated by scripts/fetch-fonts.mjs */',
  ...faces.flatMap((f) => [
    '@font-face {',
    `  font-family: '${f.family}';`,
    `  font-style: normal;`,
    `  font-weight: ${f.weight};`,
    `  font-display: swap;`,
    `  src: url('/fonts/${f.file}') format('woff2');`,
    `  unicode-range: ${f.range};`,
    '}',
    '',
  ]),
];
await mkdir(join(ROOT, 'src', 'styles'), { recursive: true });
await writeFile(CSS_OUT, lines.join('\n'));
console.log(`wrote ${faces.length} faces -> src/styles/fonts.css`);
